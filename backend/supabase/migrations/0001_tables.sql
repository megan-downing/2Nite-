create table if not exists public.app_settings (
  id                         boolean primary key default true check (id), -- single-row table
  summary_window             interval     not null,  -- how far back venue_summary looks
  price_level_1_max          numeric(6,2) not null,  -- median pint <= this  -> price_level 1 (€)
  price_level_2_max          numeric(6,2) not null,  -- median pint <= this  -> price_level 2 (€€), above -> 3 (€€€)
  rate_limit_per_venue_hour  int          not null,  -- max reports per device per venue per hour
  rate_limit_total_hour      int          not null,  -- max reports per device across all venues per hour
  outlier_baseline_window    interval     not null,  -- history used to judge outliers
  outlier_min_reports        int          not null,  -- need at least this many reports before judging
  outlier_factor             numeric(4,2) not null   -- flag if price > median*factor or < median/factor
);

insert into public.app_settings (
  id, summary_window,
  price_level_1_max, price_level_2_max,
  rate_limit_per_venue_hour, rate_limit_total_hour,
  outlier_baseline_window, outlier_min_reports, outlier_factor
) values (
  true, interval '4 hours',      -- change to '7 days' for demos
  6.00, 6.80,                    -- € up to 6.00, €€ up to 6.80, €€€ above
  5, 30,
  interval '7 days', 3, 2.5
)
on conflict (id) do update set
  summary_window            = excluded.summary_window,
  price_level_1_max         = excluded.price_level_1_max,
  price_level_2_max         = excluded.price_level_2_max,
  rate_limit_per_venue_hour = excluded.rate_limit_per_venue_hour,
  rate_limit_total_hour     = excluded.rate_limit_total_hour,
  outlier_baseline_window   = excluded.outlier_baseline_window,
  outlier_min_reports       = excluded.outlier_min_reports,
  outlier_factor            = excluded.outlier_factor;

-- -----------------------------------------------------------------------------
-- venues — added manually (SQL editor / Table editor), read-only for clients
-- -----------------------------------------------------------------------------
create table if not exists public.venues (
  id          bigint generated by default as identity primary key,
  name        text        not null check (char_length(name) between 1 and 120),
  type        text        not null check (type in ('bar', 'club')),
  music       text[]      not null default '{}'
                          check (music::text = lower(music::text)),  -- tags stored lowercase
  min_age     int         not null default 18 check (min_age between 18 and 25),
  image_url   text,
  created_at  timestamptz not null default now()
);

create unique index if not exists venues_name_key on public.venues (lower(name));

-- -----------------------------------------------------------------------------
-- reports — crowdsourced, insert-only for clients
-- -----------------------------------------------------------------------------
create table if not exists public.reports (
  id           bigint generated by default as identity primary key,
  venue_id     bigint       not null references public.venues (id) on delete cascade,
  pint_price   numeric(6,2) check (pint_price  > 0 and pint_price  <= 100),
  shot_price   numeric(6,2) check (shot_price  > 0 and shot_price  <= 100),
  mixer_price  numeric(6,2) check (mixer_price > 0 and mixer_price <= 100),
  free_entry   boolean,
  entry_fee    numeric(6,2) check (entry_fee >= 0 and entry_fee <= 100),
  created_at   timestamptz  not null default now(),
  device_id    text         not null check (char_length(device_id) between 8 and 64),
  flagged      boolean      not null default false,   -- set by trigger; flagged rows are ignored by venue_summary
  flag_reason  text,

  -- at least one useful field
  constraint reports_has_data check (
    pint_price is not null or shot_price is not null or mixer_price is not null
    or free_entry is not null or entry_fee is not null
  ),
  -- "free entry" and a positive fee contradict each other
  constraint reports_free_entry_consistent check (
    free_entry is distinct from true or coalesce(entry_fee, 0) = 0
  )
);

create index if not exists reports_venue_created_idx  on public.reports (venue_id, created_at desc);
create index if not exists reports_device_created_idx on public.reports (device_id, created_at desc);
