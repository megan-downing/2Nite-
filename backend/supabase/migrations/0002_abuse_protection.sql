-- =============================================================================
-- 0002_abuse_protection.sql  —  BEFORE INSERT trigger on reports
-- Run 2nd. Safe to re-run.
--
-- For inserts coming from the website (roles anon / authenticated):
--   * created_at is forced to now() (no back-dating or future-dating)
--   * rate limits per device_id (see app_settings):
--       - max N reports per venue per device per hour      (default 5)
--       - max M reports per device across all venues/hour  (default 30)
--     -> raises an error with hint 'rate_limited'
-- For every insert (including seed data):
--   * entry fields are normalised (fee 0 => free, fee > 0 => not free)
--   * outliers are FLAGGED, not rejected: if a price is more than
--     outlier_factor x (or less than 1/outlier_factor x) the venue's median over
--     outlier_baseline_window, the row is stored with flagged = true and
--     venue_summary ignores it. Needs outlier_min_reports reports to judge.
--
-- Note: device_id is generated by the browser, so a determined abuser can
-- rotate it. This is "keep honest people honest" protection for a hackathon.
-- =============================================================================

create or replace function public.reports_before_insert()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  s            public.app_settings%rowtype;
  is_client    boolean := current_user in ('anon', 'authenticated');
  n_venue      int;
  n_total      int;
  base_pint    numeric;
  base_shot    numeric;
  base_mixer   numeric;
  base_fee     numeric;
  n_base       int;
  reasons      text[] := '{}';
begin
  select * into s from public.app_settings where id;

  -- ---- server-controlled fields ------------------------------------------
  new.flagged     := false;
  new.flag_reason := null;
  if is_client or new.created_at is null then
    new.created_at := now();
  end if;
  new.device_id := btrim(new.device_id);

  -- ---- normalise entry info ----------------------------------------------
  if new.entry_fee is not null then
    if new.entry_fee = 0 then
      new.free_entry := coalesce(new.free_entry, true);
    else
      new.free_entry := coalesce(new.free_entry, false);
    end if;
  elsif new.free_entry is true then
    new.entry_fee := 0;
  end if;

  -- ---- rate limiting (website users only) ---------------------------------
  if is_client then
    select count(*) filter (where r.venue_id = new.venue_id), count(*)
      into n_venue, n_total
      from public.reports r
     where r.device_id = new.device_id
       and r.created_at > now() - interval '1 hour';

    if n_venue >= s.rate_limit_per_venue_hour then
      raise exception 'Rate limit: max % reports per venue per hour. Try again later.',
                      s.rate_limit_per_venue_hour
        using errcode = 'P0001', hint = 'rate_limited';
    end if;
    if n_total >= s.rate_limit_total_hour then
      raise exception 'Rate limit: max % reports per hour. Try again later.',
                      s.rate_limit_total_hour
        using errcode = 'P0001', hint = 'rate_limited';
    end if;
  end if;

  -- ---- outlier flagging ----------------------------------------------------
  select count(*),
         percentile_cont(0.5) within group (order by r.pint_price),
         percentile_cont(0.5) within group (order by r.shot_price),
         percentile_cont(0.5) within group (order by r.mixer_price),
         percentile_cont(0.5) within group (order by r.entry_fee) filter (where r.entry_fee > 0)
    into n_base, base_pint, base_shot, base_mixer, base_fee
    from public.reports r
   where r.venue_id = new.venue_id
     and not r.flagged
     and r.created_at > now() - s.outlier_baseline_window;

  if n_base >= s.outlier_min_reports then
    if new.pint_price is not null and base_pint is not null
       and (new.pint_price > base_pint * s.outlier_factor or new.pint_price < base_pint / s.outlier_factor) then
      reasons := reasons || format('pint %s vs median %s', new.pint_price, round(base_pint, 2));
    end if;
    if new.shot_price is not null and base_shot is not null
       and (new.shot_price > base_shot * s.outlier_factor or new.shot_price < base_shot / s.outlier_factor) then
      reasons := reasons || format('shot %s vs median %s', new.shot_price, round(base_shot, 2));
    end if;
    if new.mixer_price is not null and base_mixer is not null
       and (new.mixer_price > base_mixer * s.outlier_factor or new.mixer_price < base_mixer / s.outlier_factor) then
      reasons := reasons || format('mixer %s vs median %s', new.mixer_price, round(base_mixer, 2));
    end if;
    if new.entry_fee > 0 and base_fee is not null
       and new.entry_fee > base_fee * s.outlier_factor then
      reasons := reasons || format('entry fee %s vs median %s', new.entry_fee, round(base_fee, 2));
    end if;
  end if;

  if cardinality(reasons) > 0 then
    new.flagged     := true;
    new.flag_reason := 'outlier: ' || array_to_string(reasons, '; ');
  end if;

  return new;
end;
$$;

drop trigger if exists reports_before_insert on public.reports;
create trigger reports_before_insert
  before insert on public.reports
  for each row execute function public.reports_before_insert();

-- trigger function is not meant to be called directly
revoke all on function public.reports_before_insert() from public, anon, authenticated;
